  await tab('sohu').click()
  assert.equal(await previewTitle.textContent(), '实时联动标题')
  assert.match(await article.textContent(), /更新后的两平台正文/)
  await article.getByAltText('现场配图').evaluate((node) => node.decode())
  await button('跟随知乎').click()
  assert.match(await dialog.textContent(), /以 知乎 为来源/)
  await dialog.getByRole('checkbox', { name: '百家号' }).uncheck()
  await button('更新联动', dialog).click()
  await tab('zhihu').click()
  await edit()
