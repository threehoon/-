  await tab('baijiahao').click()
  assert.equal(await previewTitle.textContent(), '实时联动标题')
  await tab('sohu').click()
  assert.equal(await previewTitle.textContent(), '仅搜狐更新')
  await button('跟随知乎').click()
  await button('停止联动', dialog).click()
  await tab('zhihu').click()
  await edit()
  await title.fill('停止后只改知乎')
  await page.locator('.draft-status[data-state="saved"]').waitFor()
  await page.reload()
  await page.locator('.workspace[aria-busy="false"]').waitFor()
  assert.equal(await source.inputValue(), markdown)
