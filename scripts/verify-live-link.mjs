  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'zh-CN', reducedMotion: 'reduce' })
  page.setDefaultTimeout(5000)
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true })
  const tab = (id) => page.locator(`#platform-tab-${id}`)
  const source = page.getByRole('textbox', { name: 'Markdown 源稿' })
  const article = page.locator('.article')
  const title = page.getByRole('textbox', { name: '当前平台标题' })
  const previewTitle = page.locator('.article-title')
  const dialog = page.getByRole('dialog', { name: '实时联动' })
  const edit = () => button('编辑正文').click()
  const start = button('开始联动', dialog)
  const shot = async (name) => {
    await mkdir(out, { recursive: true })
    await page.screenshot({ path: join(out, `${name}.png`) })
  }
  async function editOpening(text) {
    const paragraph = article.locator('p').first()
    await paragraph.evaluate((node) => {
      node.closest('[contenteditable]').focus()
      const range = document.createRange()
      range.selectNodeContents(node)
      getSelection().removeAllRanges()
      getSelection().addRange(range)
    })
    await page.keyboard.insertText(text)
  }

