import { existsSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { chromium } from 'playwright-core'

const target = process.env.TARGET_URL ?? 'http://127.0.0.1:5183/'
const out = process.env.OUT_DIR ?? '.tmp/live-link'
const installed = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const executablePath = process.env.CHROME_BIN ?? (existsSync(installed) ? installed : chromium.executablePath())
const browser = await chromium.launch({ executablePath, headless: true })
const markdown = '# 原稿标题\n\n排版工作台样稿。\n\n请参考[政策说明](https://www.gov.cn/)。\n\n|项目|内容|\n|---|---|\n|甲|乙|'
