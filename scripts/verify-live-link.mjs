  await editOpening('同步前，来源已改。')
  await tab('baijiahao').click()
  assert.equal(await previewTitle.textContent(), '原稿标题')
  const defaultBaiduBody = await article.innerHTML()
  await tab('zhihu').click()
  await button('实时联动').focus()
  await page.keyboard.press('Enter')
  await dialog.waitFor()
  assert.equal(await dialog.getByRole('checkbox', { checked: true }).count(), 0)
  assert(await start.isDisabled())
  assert.equal(await page.locator(':focus').evaluate((node) => node.closest('label')?.textContent), '微信公众号')
  await page.keyboard.press('Space')
  assert(await dialog.getByRole('checkbox', { name: '微信公众号' }).isChecked())
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  assert(await button('实时联动').evaluate((node) => node === document.activeElement))
  await tab('baijiahao').click()
  assert.equal(await article.innerHTML(), defaultBaiduBody)
  await tab('zhihu').click()
  await button('实时联动').click()
  await dialog.getByRole('checkbox', { name: '百家号' }).check()
  const sohuLabel = dialog.getByText('搜狐号', { exact: true })
  const sohuCheckbox = dialog.getByRole('checkbox', { name: '搜狐号' })
  const labelBounds = await sohuLabel.boundingBox()
  assert(labelBounds)
  const labelY = labelBounds.y + labelBounds.height / 2
  await page.mouse.move(labelBounds.x + 1, labelY)
  await page.mouse.down()
  await page.mouse.move(labelBounds.x + labelBounds.width - 1, labelY, { steps: 8 })
  const summaryBounds = await dialog.locator('#live-link-summary').boundingBox()
  assert(summaryBounds)
  await page.mouse.move(labelBounds.x + labelBounds.width - 1, summaryBounds.y + 1)
  await page.mouse.up()
  assert.equal(await page.evaluate(() => getSelection().toString()), '', '拖拽平台名称不应选中文字')
  assert(!(await sohuCheckbox.isChecked()))
  assert.notEqual(await dialog.locator('#live-link-summary').evaluate((node) => getComputedStyle(node).userSelect), 'none')
  await sohuLabel.click()
  assert(await sohuCheckbox.isChecked())
  await sohuLabel.click()
  assert(!(await sohuCheckbox.isChecked()))
  await sohuLabel.click()
  for (const [width, height] of [[1440, 900], [1024, 768], [390, 640]]) {
    await page.setViewportSize({ width, height })
    const bounds = await dialog.boundingBox()
    assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= height)
    assert(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth))
    const confirmBounds = await start.boundingBox()
    assert(confirmBounds && confirmBounds.y + confirmBounds.height <= bounds.y + bounds.height, '确认按钮应完整可见')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await shot(`targets-${width}`)
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await start.click()
  await button('联动中 · 2 个平台').waitFor()
  await tab('baijiahao').click()
  assert.equal(await previewTitle.textContent(), '选择前的知乎标题')
  assert.match(await article.textContent(), /同步前，来源已改/)
  assert.equal(await article.locator('table, a').count(), 0)
  await page.getByText(/表格已按原行序转为/u).first().waitFor()
  await tab('sohu').click()
  assert.equal(await article.locator('table').count(), 1)
  assert.equal(await article.locator('a').getAttribute('href'), 'https://www.gov.cn/')
  await tab('qq').click()
  assert.equal(await previewTitle.textContent(), '未选腾讯草稿')
  assert.match(await article.textContent(), /排版工作台样稿/)

  await tab('zhihu').click()
